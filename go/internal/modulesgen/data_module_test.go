func TestDataModuleRejectsInvalidDataSourceAttributesBeforeWriting(t *testing.T) {
	validID := metadata.JsonObject{"computed": true, "type": "number"}
	cases := []struct {
		name               string
		attributes         metadata.JsonObject
		wantErrorFragments []string
	}{
		{
			name: "missing name field attribute",
			attributes: metadata.JsonObject{
				"id":   metadata.JsonObject{"computed": true, "type": "number"},
				"name": metadata.JsonObject{"optional": true, "type": "string"},
			},
			wantErrorFragments: []string{"missing input attribute", "display_name"},
		},
		{
			name: "computed-only name field",
			attributes: metadata.JsonObject{
				"display_name": metadata.JsonObject{"computed": true, "type": "string"},
				"id":           validID,
			},
			wantErrorFragments: []string{"computed-only", "display_name"},
		},
		{
			name: "non-string name field",
			attributes: metadata.JsonObject{
				"display_name": metadata.JsonObject{"optional": true, "type": "number"},
				"id":           validID,
			},
			wantErrorFragments: []string{"string-typed", "display_name"},
		},
		{
			name: "missing id",
			attributes: metadata.JsonObject{
				"display_name": metadata.JsonObject{"optional": true, "type": "string"},
			},
			wantErrorFragments: []string{"missing readable id attribute"},
		},
	}

	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			root := syntheticDataModuleRoot(t, dataModuleFixtureOptions{
				lookupNameField:         "display_name",
				includeLookupSource:     true,
				includeDataSourceSchema: true,
				dataSourceAttributes:    testCase.attributes,
			})
			output := t.TempDir()
			_, err := GenerateModule(root, "zia_location_groups", GenerateModuleOptions{
				OutputRoot: output,
				FormatHCL:  IdentityFormatter,
			})
			if err == nil {
				t.Fatalf("GenerateModule(%q, %s) error = nil, want validation failure", "zia_location_groups", testCase.name)
			}
			for _, fragment := range testCase.wantErrorFragments {
				if !strings.Contains(err.Error(), fragment) {
					t.Errorf("GenerateModule(%q, %s) error = %q, want fragment %q", "zia_location_groups", testCase.name, err, fragment)
				}
			}
			entries, readErr := os.ReadDir(output)
			if readErr != nil {
				t.Fatalf("GenerateModule(%q, %s) output directory read error = %v, want empty directory", "zia_location_groups", testCase.name, readErr)
			}
			if len(entries) != 0 {
				t.Errorf("GenerateModule(%q, %s) wrote %d output entries, want 0 before validation succeeds", "zia_location_groups", testCase.name, len(entries))
			}
		})
	}
}

