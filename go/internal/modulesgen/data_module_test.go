func TestActiveDataReferentModulesGenerateAndValidate(t *testing.T) {
	root := syntheticDataModuleRoot(t, dataModuleFixtureOptions{
		lookupNameField:         "name",
		includeLookupSource:     true,
		includeDataSourceSchema: true,
	})
	if got := ActiveGeneratedResourceTypes(root); len(got) != 0 {
		t.Fatalf("ActiveGeneratedResourceTypes(data-only fixture) = %v, want no generated resource types", got)
	}
	wantTypes := []string{"zia_location_groups"}
	if got := ActiveDataReferentResourceTypes(root); !reflect.DeepEqual(got, wantTypes) {
		t.Fatalf("ActiveDataReferentResourceTypes(data-only fixture) = %v, want %v", got, wantTypes)
	}
	if got := ActiveModuleResourceTypes(root); !reflect.DeepEqual(got, wantTypes) {
		t.Fatalf("ActiveModuleResourceTypes(data-only fixture) = %v, want %v", got, wantTypes)
	}

	output := t.TempDir()
	generated, err := GenerateActiveModules(root, GenerateModuleOptions{
		OutputRoot: output,
		FormatHCL:  NewHCLFormatter(),
	})
	if err != nil {
		t.Fatalf("GenerateActiveModules(data-only fixture): %v", err)
	}
	if got := len(generated); got != 1 {
		t.Fatalf("GenerateActiveModules(data-only fixture) returned %d modules, want 1", got)
	}
	if generated[0].ResourceType != "zia_location_groups" {
		t.Errorf("GenerateActiveModules(data-only fixture)[0].ResourceType = %q, want zia_location_groups", generated[0].ResourceType)
	}
	generatedMain, err := os.ReadFile(filepath.Join(output, "zia_location_groups", string(FileMain)))
	if err != nil {
		t.Fatalf("ReadFile generated data module main.tf: %v", err)
	}
	wantGeneratedMain := "# GENERATED by iw modules generate from packs/zia/schemas/provider/zia.json — do not edit.\n# Regenerate: make gen-modules\n\ndata \"zia_location_groups\" \"items\" {\n  for_each = var.items\n  name     = each.value.name\n}\n\noutput \"items\" {\n  description = \"All read-only zia_location_groups data source objects, keyed as in var.items.\"\n  value       = data.zia_location_groups.items\n}\n"
	if string(generatedMain) != wantGeneratedMain {
		t.Errorf("GenerateActiveModules(data-only fixture).main.tf = %q, want %q", generatedMain, wantGeneratedMain)
	}
	generatedVariables, err := os.ReadFile(filepath.Join(output, "zia_location_groups", string(FileVariables)))
	if err != nil {
		t.Fatalf("ReadFile generated data module variables.tf: %v", err)
	}
	wantGeneratedVariables := "# GENERATED by iw modules generate from packs/zia/schemas/provider/zia.json — do not edit.\n# Regenerate: make gen-modules\n\nvariable \"items\" {\n  description = \"zia_location_groups instances, keyed by a stable identifier.\"\n  type = map(object({\n    name = string\n  }))\n}\n"
	if string(generatedVariables) != wantGeneratedVariables {
		t.Errorf("GenerateActiveModules(data-only fixture).variables.tf = %q, want %q", generatedVariables, wantGeneratedVariables)
	}
	validated, err := ValidateGeneratedModuleTree(output, wantTypes)
	if err != nil {
		t.Fatalf("ValidateGeneratedModuleTree(data-only fixture): %v", err)
	}
	if !reflect.DeepEqual(validated, wantTypes) {
		t.Errorf("ValidateGeneratedModuleTree(data-only fixture) = %v, want %v", validated, wantTypes)
	}
}
