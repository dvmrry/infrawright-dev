type dataModuleFixtureOptions struct {
	lookupNameField         string
	includeLookupSource     bool
	includeDataSourceSchema bool
	dataSourceAttributes    metadata.JsonObject
}

func writeSyntheticModulePack(
	t *testing.T,
	root string,
	name string,
	manifest metadata.JsonObject,
	registry metadata.JsonObject,
	resourceSchemas metadata.JsonObject,
	dataSourceSchemas ...metadata.JsonObject,
) {
	t.Helper()
	dataSources := metadata.JsonObject{}
	if len(dataSourceSchemas) > 1 {
		t.Fatalf("writeSyntheticModulePack(%q) received %d data_source_schemas values, want at most one", name, len(dataSourceSchemas))
	}
	if len(dataSourceSchemas) == 1 && dataSourceSchemas[0] != nil {
		dataSources = dataSourceSchemas[0]
	}
	writeJSONFile(t, filepath.Join(root, name, "pack.json"), manifest)
	writeJSONFile(t, filepath.Join(root, name, "registry.json"), registry)
	writeJSONFile(t, filepath.Join(root, name, "schemas", "provider", name+".json"), metadata.JsonObject{
		"resource_schemas":    resourceSchemas,
		"data_source_schemas": dataSources,
	})
}

func syntheticDataModuleLoadOptions(t *testing.T, options dataModuleFixtureOptions) metadata.LoadPackRootOptions {
	t.Helper()

	packsRoot := t.TempDir()
	manifest := metadata.JsonObject{
		"pin":               "1.0.0",
		"provider_prefixes": metadata.JsonObject{"zia_": "zia"},
		"provider_sources":  metadata.JsonObject{"zia": "zscaler/zia"},
	}
	if options.includeLookupSource {
		nameField := options.lookupNameField
		if nameField == "" {
			nameField = "name"
		}
		manifest["lookup_sources"] = metadata.JsonObject{
			"zia_location_groups": metadata.JsonObject{"name_field": nameField},
		}
	}

	const dataReferentType = "zia_location_groups"
	registry := metadata.JsonObject{
		dataReferentType: metadata.JsonObject{
			"data_referent": true,
			"fetch": metadata.JsonObject{
				"pagination": "zia",
				"path":       "locations/groups",
			},
			"product": "zia",
		},
	}
	dataSourceSchemas := metadata.JsonObject{}
	if options.includeDataSourceSchema {
		attributes := options.dataSourceAttributes
		if attributes == nil {
			attributes = metadata.JsonObject{
				"id": metadata.JsonObject{
					"computed": true,
					"type":     "number",
				},
				"name": metadata.JsonObject{
					"optional": true,
					"type":     "string",
				},
			}
		}
		dataSourceSchemas[dataReferentType] = metadata.JsonObject{
			"block": metadata.JsonObject{
				"attributes": attributes,
			},
		}
	}

	writeSyntheticModulePack(t, packsRoot, "zia", manifest, registry, metadata.JsonObject{}, dataSourceSchemas)
	profilePath := packsRoot + "/synthetic.packset.json"
	writeJSONFile(t, profilePath, metadata.JsonObject{
		"kind":    metadata.PackSetKind,
		"version": 1,
		"packs":   []any{"zia"},
		"shared":  []any{},
	})

	return metadata.LoadPackRootOptions{
		PacksRoot:   packsRoot,
		ProfilePath: &profilePath,
	}
}

